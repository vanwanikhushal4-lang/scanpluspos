CREATE TABLE IF NOT EXISTS enrollments (
 code_hash VARCHAR(64) PRIMARY KEY, label VARCHAR(80) NOT NULL,
 expected_serial VARCHAR(80) NOT NULL, expires_at TIMESTAMP NOT NULL, consumed BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS devices (
 id VARCHAR(36) PRIMARY KEY, token_hash VARCHAR(64) NOT NULL UNIQUE,
 label VARCHAR(80) NOT NULL, serial VARCHAR(80) NOT NULL, model VARCHAR(80) NOT NULL,
 version VARCHAR(40) NOT NULL, enrolled_at TIMESTAMP NOT NULL, last_seen TIMESTAMP,
 enabled BOOLEAN, owner_active BOOLEAN, usb_sealed BOOLEAN, bridge_available BOOLEAN,
 detail VARCHAR(2000), revoked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS commands (
 id VARCHAR(36) PRIMARY KEY, device_id VARCHAR(36) NOT NULL REFERENCES devices(id),
 request_id VARCHAR(36) NOT NULL, enabled BOOLEAN NOT NULL,
 created_at TIMESTAMP NOT NULL, expires_at TIMESTAMP NOT NULL,
 state VARCHAR(16) NOT NULL, detail VARCHAR(2000),
 UNIQUE(device_id, request_id)
);
CREATE INDEX IF NOT EXISTS commands_device_state ON commands(device_id,state,created_at);
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_time TIMESTAMP NOT NULL, actor VARCHAR(80) NOT NULL, action VARCHAR(80) NOT NULL,
 device_id VARCHAR(36), command_id VARCHAR(36), detail VARCHAR(2000) NOT NULL
);
CREATE TABLE IF NOT EXISTS app_inventories (
 device_id VARCHAR(36) PRIMARY KEY REFERENCES devices(id), reported_at TIMESTAMP NOT NULL, inventory_json CLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS app_apks (
 id VARCHAR(36) PRIMARY KEY, filename VARCHAR(160) NOT NULL, size_bytes BIGINT NOT NULL,
 sha256 VARCHAR(64) NOT NULL, uploaded_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS app_commands (
 id VARCHAR(36) PRIMARY KEY, device_id VARCHAR(36) NOT NULL REFERENCES devices(id), request_id VARCHAR(36) NOT NULL,
 action VARCHAR(32) NOT NULL, package_name VARCHAR(180), permission_name VARCHAR(200), artifact_id VARCHAR(36) REFERENCES app_apks(id),
 payload VARCHAR(2000) NOT NULL, created_at TIMESTAMP NOT NULL, expires_at TIMESTAMP NOT NULL, started_at TIMESTAMP,
 completed_at TIMESTAMP, state VARCHAR(16) NOT NULL, detail VARCHAR(2000), result_json CLOB,
 UNIQUE(device_id,request_id)
);
CREATE INDEX IF NOT EXISTS app_commands_device_state ON app_commands(device_id,state,created_at);
